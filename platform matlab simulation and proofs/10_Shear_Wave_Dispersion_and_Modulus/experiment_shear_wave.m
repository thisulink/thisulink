%% THISULINK PLANTAR BIOMECHANICAL SWE PLATFORM
% Experiment 10: Shear Wave Dispersion, Phase Velocity & Young's Modulus
% Dual-Pickup Accelerometer Phase-Difference Elastography Pipeline
%
% Part A - Nominal 50 Hz measurement: exciter response from the ODE model
%          (common/tissue_model.m), propagation to both pickups
%          (common/shear_wave_propagation_model.m), ADXL355 digitisation
%          (05_Sensor_Simulation/sensor_model.m), phase-difference speed
%          c = w*dx/dphi and apparent modulus E = 3*rho*c^2.
% Part B - Stepped-sine sweep (20-300 Hz): wrapped vs frequency-unwrapped
%          phase difference, usable band limited by attenuation/SNR.
% Part C - Kelvin-Voigt fit (mu, eta) to the measured dispersion curve,
%          E = 3*mu (removes the viscous bias of the single-frequency value).
%
% SIMULATION ONLY: synthetic signals generated by the same models that are
% used for reconstruction ("inverse crime"), so the accuracy printed here is
% an upper bound, not an expected in-vivo accuracy.

% (No clear/clc/close all here: the master runner executes every experiment
%  in its own workspace, and clearing would break callers.)

%% Path Setup
expDir = fileparts(mfilename('fullpath'));
if isempty(expDir), expDir = pwd; end
projectRoot = fileparts(expDir);
addpath(fullfile(projectRoot, 'common'));
addpath(fullfile(projectRoot, '05_Sensor_Simulation'));

%% Load Calibrated Parameters
simulation_parameters;

%% Dual Pickup Geometry
x1 = x_sensor1;   % 105 mm
x2 = x_sensor2;   % 145 mm
dx = delta_x;     % 40 mm

%% Diagnostic Classes
cls_name = {'Healthy Control', 'Early Glycation', 'Diabetic Neuropathy'};
cls_k    = [k_A,   k_B,   k_C];
cls_c    = [c_A,   c_B,   c_C];
cls_mu   = [mu_A,  mu_B,  mu_C];
cls_eta  = [eta_A, eta_B, eta_C];
numClasses = 3;

sensor_params.range_g       = sensor_range_g;
sensor_params.bits          = sensor_bits;
sensor_params.bandwidth     = sensor_bandwidth;
sensor_params.noise_density = sensor_noise_dens;
sensor_params.bias          = sensor_bias;

% Kelvin-Voigt phase velocity (same formula as the shared propagation model)
kv_cs = @(f, mu, eta) sqrt((2 * (mu.^2 + (2*pi*f*eta).^2)) ./ ...
    (rho_tissue * (mu + sqrt(mu.^2 + (2*pi*f*eta).^2))));

% Analysis window: skip the first 0.2 s (wave onset / ODE transient), then
% use an integer number of excitation periods.
t_skip = 0.2;

%% =====================================================================
%% PART A: nominal 50 Hz dual-pickup phase-difference measurement
%% =====================================================================
x0 = [0; 0];
w0 = 2 * pi * f_exc;
time_signals_1 = zeros(length(t), numClasses);
time_signals_2 = zeros(length(t), numClasses);
cs_50_est  = zeros(numClasses, 1);
cs_50_true = zeros(numClasses, 1);
E_50_app   = zeros(numClasses, 1);
tof_50_ms  = zeros(numClasses, 1);

for i = 1:numClasses
    [t_sim, X] = ode45(@(tt, x) tissue_model(tt, x, m, cls_c(i), cls_k(i), F0, f_exc), t, x0);
    acc_src = (F0 * sin(w0 * t_sim) - cls_c(i) * X(:, 2) - cls_k(i) * X(:, 1)) / m;

    u1_true = shear_wave_propagation_model(t_sim, acc_src, x1, cls_mu(i), cls_eta(i), rho_tissue, f_exc);
    u2_true = shear_wave_propagation_model(t_sim, acc_src, x2, cls_mu(i), cls_eta(i), rho_tissue, f_exc);

    sensor_params.seed = 1000 + 10*i + 1;
    u1_meas = sensor_model(u1_true, sensor_params);
    sensor_params.seed = 1000 + 10*i + 2;
    u2_meas = sensor_model(u2_true, sensor_params);
    time_signals_1(:, i) = u1_meas;
    time_signals_2(:, i) = u2_meas;

    [X1, X2] = fourier_pair(t_sim, u1_meas, u2_meas, f_exc, t_skip);
    dphi = mod(angle(X1 * conj(X2)), 2*pi);  % distal lags proximal; valid while dphi < 2*pi

    cs_50_est(i)  = w0 * dx / dphi;
    cs_50_true(i) = kv_cs(f_exc, cls_mu(i), cls_eta(i));
    E_50_app(i)   = 3 * rho_tissue * cs_50_est(i)^2 / 1000;   % kPa
    tof_50_ms(i)  = dphi / w0 * 1000;
end

%% =====================================================================
%% PART B: stepped-sine sweep, wrapped vs unwrapped phase
%% =====================================================================
f_sweep = 20:10:f_end;        % 20 ... 300 Hz
numF = length(f_sweep);
dphi_wrapped = zeros(numF, numClasses);   % in (-pi, pi]
snr_dist_dB  = zeros(numF, numClasses);   % SNR of the distal Fourier coefficient
noise_rms    = sensor_noise_dens * sqrt(sensor_bandwidth);
snr_min_dB   = 20;                        % usable if distal SNR >= 20 dB

for i = 1:numClasses
    for s = 1:numF
        f  = f_sweep(s);
        w  = 2 * pi * f;
        % steady-state exciter acceleration amplitude from the FRF
        A_src = abs(-(w^2) / ((cls_k(i) - m*w^2) + 1i*cls_c(i)*w)) * F0;
        src = A_src * sin(w * t);
        u1_true = shear_wave_propagation_model(t, src, x1, cls_mu(i), cls_eta(i), rho_tissue, f);
        u2_true = shear_wave_propagation_model(t, src, x2, cls_mu(i), cls_eta(i), rho_tissue, f);
        sensor_params.seed = 20000 + 1000*i + 2*s;
        u1_meas = sensor_model(u1_true, sensor_params);
        sensor_params.seed = 20000 + 1000*i + 2*s + 1;
        u2_meas = sensor_model(u2_true, sensor_params);

        [X1, X2, nWin] = fourier_pair(t, u1_meas, u2_meas, f, t_skip);
        dphi_wrapped(s, i) = angle(X1 * conj(X2));
        % amplitude of the distal component vs its noise floor (noise_rms*sqrt(2/N))
        snr_dist_dB(s, i) = 20 * log10(abs(X2) / (noise_rms * sqrt(2 / nWin)));
    end
end

% Usable band = contiguous run of frequencies from the lowest one with SNR >= threshold
usable = false(numF, numClasses);
for i = 1:numClasses
    s = 1;
    while s <= numF && snr_dist_dB(s, i) >= snr_min_dB
        usable(s, i) = true;
        s = s + 1;
    end
end

dphi_unwrapped = nan(numF, numClasses);
cs_unwrapped   = nan(numF, numClasses);
cs_naive       = zeros(numF, numClasses);   % single-frequency estimate, no unwrapping
cs_theory      = zeros(numF, numClasses);
for i = 1:numClasses
    cs_theory(:, i) = kv_cs(f_sweep(:), cls_mu(i), cls_eta(i));
    % naive estimator: wrapped phase in (-pi, pi], no unwrapping
    cs_naive(:, i) = 2*pi*f_sweep(:)*dx ./ dphi_wrapped(:, i);
    u = usable(:, i);
    if any(u)
        % The lowest frequency (20 Hz) has dphi < pi for all classes, so
        % unwrapping along frequency starts on the correct branch.
        dphi_unwrapped(u, i) = unwrap(dphi_wrapped(u, i));
        cs_unwrapped(u, i)   = 2*pi*f_sweep(u)'*dx ./ dphi_unwrapped(u, i);
    end
end

%% =====================================================================
%% PART C: Kelvin-Voigt fit of (mu, eta) to the unwrapped dispersion curve
%% =====================================================================
mu_fit  = nan(numClasses, 1);
eta_fit = nan(numClasses, 1);
fit_opts = optimset('TolX', 1e-10, 'TolFun', 1e-14, 'MaxFunEvals', 20000, 'MaxIter', 20000);
for i = 1:numClasses
    u = usable(:, i);
    if sum(u) >= 3
        fu = f_sweep(u)';
        cu = cs_unwrapped(u, i);
        cost = @(p) sum(((kv_cs(fu, exp(p(1)), exp(p(2))) - cu) ./ cu).^2);
        p0 = [log(rho_tissue * cu(1)^2), log(10)];
        p_hat = fminsearch(cost, p0, fit_opts);
        mu_fit(i)  = exp(p_hat(1));
        eta_fit(i) = exp(p_hat(2));
    end
end
E_true = 3 * cls_mu(:) / 1000;   % kPa
E_fit  = 3 * mu_fit / 1000;      % kPa

%% Console Output
fprintf('\n========================================================================\n');
fprintf('  THISULINK EXPERIMENT 10: PLANTAR SWE DISPERSION & MODULUS RECONSTRUCTION\n');
fprintf('  (SIMULATION - synthetic signals, same forward model used for inversion)\n');
fprintf('========================================================================\n');
fprintf('Gauge Separation dx           : %.1f mm (x1 = %.0f mm, x2 = %.0f mm)\n', dx*1000, x1*1000, x2*1000);
fprintf('Sensor                        : ADXL355, ODR %.0f Hz, noise BW %.0f Hz\n', sensor_odr, sensor_bandwidth);
fprintf('\nPART A - single frequency (%.0f Hz), E_app = 3*rho*c^2:\n', f_exc);
fprintf('%-20s %8s %8s %8s %9s %9s %9s\n', 'Class', 'c_true', 'c_est', 'ToF', 'E=3mu', 'E_app', 'E_app err');
fprintf('%-20s %8s %8s %8s %9s %9s %9s\n', '', '(m/s)', '(m/s)', '(ms)', '(kPa)', '(kPa)', '(%)');
for i = 1:numClasses
    fprintf('%-20s %8.3f %8.3f %8.2f %9.1f %9.1f %+9.2f\n', cls_name{i}, cs_50_true(i), cs_50_est(i), ...
        tof_50_ms(i), E_true(i), E_50_app(i), (E_50_app(i) - E_true(i)) / E_true(i) * 100);
end
fprintf('  (c_true is the viscoelastic phase velocity at %.0f Hz; E_app is biased high\n', f_exc);
fprintf('   because viscosity raises the phase velocity above sqrt(mu/rho).)\n');

fprintf('\nPART B - stepped sine %d-%d Hz (usable = distal SNR >= %d dB):\n', f_sweep(1), f_sweep(end), snr_min_dB);
for i = 1:numClasses
    u = usable(:, i);
    f_pi = cs_theory(:, i) * 1 ./ (2*dx);          % frequency where dphi = pi
    idx_pi = find(f_sweep(:) >= f_pi, 1);
    if any(u)
        f_hi = f_sweep(find(u, 1, 'last'));
        err_unw = max(abs(cs_unwrapped(u, i) - cs_theory(u, i)) ./ cs_theory(u, i)) * 100;
        err_naive = max(abs(cs_naive(u, i) - cs_theory(u, i)) ./ cs_theory(u, i)) * 100;
    else
        f_hi = NaN; err_unw = NaN; err_naive = NaN;
    end
    if isempty(idx_pi), f_pi_txt = '> sweep'; else, f_pi_txt = sprintf('%d Hz', f_sweep(idx_pi)); end
    fprintf('  %-20s usable %3d-%3.0f Hz | dphi > pi from %-8s | max |c err| unwrapped %5.2f%%, wrapped %6.0f%%\n', ...
        cls_name{i}, f_sweep(1), f_hi, f_pi_txt, err_unw, err_naive);
end

fprintf('\nPART C - Kelvin-Voigt fit over the usable band:\n');
fprintf('%-20s %9s %9s %9s %9s %9s %9s %8s\n', 'Class', 'mu_true', 'mu_fit', 'eta_true', 'eta_fit', 'E_true', 'E_fit', 'E err');
fprintf('%-20s %9s %9s %9s %9s %9s %9s %8s\n', '', '(kPa)', '(kPa)', '(Pa.s)', '(Pa.s)', '(kPa)', '(kPa)', '(%)');
for i = 1:numClasses
    fprintf('%-20s %9.2f %9.2f %9.2f %9.2f %9.1f %9.1f %+8.2f\n', cls_name{i}, cls_mu(i)/1000, mu_fit(i)/1000, ...
        cls_eta(i), eta_fit(i), E_true(i), E_fit(i), (E_fit(i) - E_true(i)) / E_true(i) * 100);
end
fprintf('LIMITATIONS: 1-D narrow-band propagation model; attenuation limits the usable\n');
fprintf('band well below 300 Hz at x2 = 145 mm; no coupling, geometry or layer effects.\n');
fprintf('========================================================================\n\n');

